#!/usr/bin/env python3
"""Mutation testing for the correctness checks.

Generates single-change mutants of the service's editable source with fixed rules (no hand
picking), runs the runner's correctness-only `check` on each, and reports which checks catch
them: the golden answers, the response invariants and the baseline comparison on sampled requests.

    python3 scripts/mutation-test.py                               # local runner binary
    python3 scripts/mutation-test.py --runner-image aiops-runner:local
    python3 scripts/mutation-test.py --list                        # print the mutants only

A mutant that survives every check is either a gap in the checks or an equivalent mutant (a
change that cannot alter any response); survivors are listed for review.
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "fixtures/orders-api"
FILES = ["src/repo.rs", "src/model.rs"]

# (name, pattern, replacement). Each match of the pattern in a code line is one mutant.
OPERATORS = [
    ("sql: DESC -> ASC", r"\bDESC\b", "ASC"),
    ("sql: drop the id tie-break", r", id DESC", ""),
    ("sql: = -> >=", r"(\w+) = \$(\d)", r"\1 >= $\2"),
    ("sql: = -> <>", r"(\w+) = \$(\d)", r"\1 <> $\2"),
    ("sql: drop item order", r" ORDER BY id\"", '"'),
    ("sql: swap LIMIT and OFFSET", r"LIMIT \$2 OFFSET \$3", "LIMIT $3 OFFSET $2"),
    ("bind: +1", r"\.bind\(([a-z_.]+)\)", r".bind(\1 + 1)"),
    ("bind: -1", r"\.bind\(([a-z_.]+)\)", r".bind(\1 - 1)"),
    ("negate: is_some -> is_none", r"is_some\(\)", "is_none()"),
    ("arith: * -> +", r" \* ", " + "),
    ("count: len + 1", r"\.len\(\) as i64", ".len() as i64 + 1"),
    ("sum: first line only", r"\.sum\(\)", ".take(1).sum()"),
    ("loop: skip the first", r"for (\w+) in (\w+) \{", r"for \1 in \2.into_iter().skip(1) {"),
    ("loop: reverse", r"for (\w+) in (\w+) \{", r"for \1 in \2.into_iter().rev() {"),
    ("alloc: with_capacity -> new", r"Vec::with_capacity\([^()]*(?:\([^()]*\))?[^()]*\)", "Vec::new()"),
    ("delete: push of an order", r"^(\s+)views\.push\(.*\);$", r"\1// (removed)"),
]


def generate():
    mutants = []
    for rel in FILES:
        text = (SOURCE / rel).read_text()
        lines = text.split("\n")
        for no, line in enumerate(lines):
            if line.strip().startswith("//"):
                continue
            for name, pattern, repl in OPERATORS:
                for m in re.finditer(pattern, line):
                    mutated = line[: m.start()] + m.expand(repl) + line[m.end():]
                    if mutated == line:
                        continue
                    # Widen the search upwards until it is unique in the file.
                    start = no
                    while text.count("\n".join(lines[start : no + 1])) != 1 and start > 0:
                        start -= 1
                    search = "\n".join(lines[start : no + 1])
                    replace = "\n".join(lines[start:no] + [mutated])
                    mid = f"m{len(mutants) + 1:02d}"
                    mutants.append({
                        "id": mid, "operator": name, "file": rel, "line": no + 1,
                        "before": line.strip(), "after": mutated.strip(),
                        "patch": {
                            "summary": f"Mutant {mid}: {name} at {rel}:{no + 1}. Generated by scripts/mutation-test.py.",
                            "edits": [{"path": rel, "search": search, "replace": replace}],
                        },
                    })
    return mutants


def failed(report):
    return bool(report) and report.get("total", 0) > 0 and report["passed"] < report["total"]


def classify(report):
    if report.get("patch_error"):
        return "invalid", []
    build = report.get("build") or {}
    if not build.get("ok"):
        return "stillborn", []
    if report.get("execution_error"):
        return "error", [report["execution_error"][:120]]
    if failed(report.get("baseline_correctness")) or failed(report.get("baseline_invariants")):
        return "error", ["the baseline failed its own checks"]
    caught = [name for name, key in (("golden", "correctness"), ("invariants", "invariants"), ("sample", "sample"))
              if failed(report.get(key))]
    return ("killed" if caught else "survived"), caught


def run_check(args, patch_path, out_path, work):
    if args.runner_image:
        cmd = ["docker", "run", "--rm", "--network", "none", "-v", f"{patch_path.parent}:/mutants:ro",
               args.runner_image, "aiops-runner", "check", "--patch", f"/mutants/{patch_path.name}"]
        env = os.environ
    else:
        cmd = [str(args.runner_bin)]
        if os.geteuid() == 0:
            cmd += ["--pg-user", "postgres"]
        cmd += ["check", "--patch", str(patch_path)]
        env = dict(os.environ, AIOPS_WORK_DIR=str(work),
                   AIOPS_TARGET_DIR=os.environ.get("AIOPS_TARGET_DIR", str(ROOT / ".work/target")))
    with open(out_path, "w") as out, open(out_path.with_suffix(".log"), "w") as log:
        status = subprocess.run(cmd, stdout=out, stderr=log, env=env, cwd=ROOT).returncode
    return status


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runner-image")
    ap.add_argument("--runner-bin", default=str(ROOT / "target/release/aiops-runner"))
    ap.add_argument("--out", default=str(ROOT / ".work/mutation"))
    ap.add_argument("--only", default="", help="run mutants whose id or operator contains this")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()

    mutants = [m for m in generate() if args.only in m["id"] or args.only in m["operator"]]
    if args.list:
        for m in mutants:
            print(f'{m["id"]}  {m["operator"]:<30} {m["file"]}:{m["line"]}  {m["after"][:90]}')
        print(f"{len(mutants)} mutants")
        return 0

    out = pathlib.Path(args.out)
    shutil.rmtree(out, ignore_errors=True)
    (out / "patches").mkdir(parents=True)
    work = out / "work"
    work.mkdir()
    os.chmod(work, 0o777)
    os.chmod(out / "patches", 0o755)

    results = []
    for m in mutants:
        patch_path = out / "patches" / f'{m["id"]}.json'
        patch_path.write_text(json.dumps(m["patch"], indent=2) + "\n")
        os.chmod(patch_path, 0o644)
        started = time.time()
        status = run_check(args, patch_path, out / f'{m["id"]}.json', work)
        try:
            report = json.loads((out / f'{m["id"]}.json').read_text())
            result, caught = classify(report)
        except (ValueError, OSError):
            result, caught = "error", [f"runner exited {status}"]
        row = {k: m[k] for k in ("id", "operator", "file", "line", "before", "after")}
        row.update(result=result, caught_by=caught, seconds=round(time.time() - started))
        results.append(row)
        print(f'{m["id"]}  {result:<9} {",".join(caught) or "-":<26} {m["operator"]:<30} '
              f'{m["file"]}:{m["line"]}  ({row["seconds"]}s)', flush=True)

    shutil.rmtree(work, ignore_errors=True)
    valid = [r for r in results if r["result"] in ("killed", "survived")]
    killed = [r for r in valid if r["result"] == "killed"]
    by_golden = [r for r in valid if "golden" in r["caught_by"]]
    survivors = [r for r in valid if r["result"] == "survived"]
    other = [r for r in results if r not in valid]
    pct = lambda a, b: f"{100 * a / b:.0f}%" if b else "n/a"
    summary = [
        f"{len(results)} mutants: {len(valid)} compiled and ran, {len(other)} did not "
        f"({', '.join(sorted({r['result'] for r in other})) or 'none'})",
        f"golden answers alone: {len(by_golden)}/{len(valid)} killed ({pct(len(by_golden), len(valid))})",
        f"golden + invariants + sample: {len(killed)}/{len(valid)} killed ({pct(len(killed), len(valid))})",
    ]
    lines = ["| id | operator | location | change | result | caught by |", "| --- | --- | --- | --- | --- | --- |"]
    for r in results:
        change = r["after"].replace("|", "\\|")[:80]
        lines.append(f'| {r["id"]} | {r["operator"]} | {r["file"]}:{r["line"]} | `{change}` | {r["result"]} | '
                     f'{", ".join(r["caught_by"]) or "-"} |')
    (out / "results.json").write_text(json.dumps(results, indent=2) + "\n")
    (out / "summary.md").write_text("\n".join(summary) + "\n\n" + "\n".join(lines) + "\n")
    print("\n" + "\n".join(summary))
    for r in survivors:
        print(f'survived: {r["id"]} {r["operator"]} {r["file"]}:{r["line"]}: {r["after"][:100]}')
    print(f"table: {out / 'summary.md'}")
    return 1 if any(r["result"] == "error" for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
